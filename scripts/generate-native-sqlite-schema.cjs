#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "prisma", "schema.prisma");
const target = path.join(root, "prisma", "schema.native.prisma");

function buildNativeSqliteSchema(input) {
  return input
    .replace(
      /datasource\s+db\s+\{[\s\S]*?\}/,
      `datasource db {
  provider = "sqlite"
}`,
    )
    .replace(/\s+@db\.[A-Za-z]+(?:\([^)]*\))?/g, "");
}

const sourceText = fs.readFileSync(source, "utf8");
const output = `// Generated by scripts/generate-native-sqlite-schema.cjs.
// Do not edit by hand. Update prisma/schema.prisma, then regenerate.

${buildNativeSqliteSchema(sourceText)}`;

fs.writeFileSync(target, output.replace(/\r\n/g, "\n"), "utf8");
console.log(`Generated ${path.relative(root, target)}`);
